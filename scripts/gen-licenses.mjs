#!/usr/bin/env node
// Generates THIRD-PARTY-LICENSES.md from license-checker JSON on stdin.
//
// Usage (see package.json "licenses:doc"):
//   license-checker-rseidelsohn --production --excludePrivatePackages --json \
//     | node scripts/gen-licenses.mjs
//
// Only PRODUCTION dependencies are listed — those are what ship in dist/ and
// are therefore the licenses that legally matter for distribution. Dev tooling
// (Vite, ESLint, Playwright, etc.) is not distributed and is excluded.

import { readFileSync, writeFileSync } from 'node:fs';

const raw = readFileSync(0, 'utf8'); // fd 0 = stdin
const data = JSON.parse(raw || '{}');

// Keys look like "name@version" or "@scope/name@version" — split on the LAST '@'.
function splitNV(key) {
  const at = key.lastIndexOf('@');
  return at <= 0 ? [key, ''] : [key.slice(0, at), key.slice(at + 1)];
}

const rows = Object.entries(data)
  .map(([key, v]) => {
    const [name, version] = splitNV(key);
    return {
      name,
      version,
      license: v.licenses || 'UNKNOWN',
      repo: (v.repository || '').replace(/^git\+/, '').replace(/\.git$/, ''),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// Summary: license -> count
const counts = {};
for (const r of rows) counts[r.license] = (counts[r.license] || 0) + 1;
const summary = Object.entries(counts).sort((a, b) => b[1] - a[1]);

const date = new Date().toISOString().slice(0, 10);
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');

const out = `# Third-Party Licenses

*Auto-generated by \`npm run licenses:doc\` — do not edit by hand.*

This is the license inventory of every **production** dependency that ships in
the built application (\`dist/\`). Development-only tooling (Vite, ESLint,
Playwright, TypeScript, Wrangler, etc.) is not distributed and is intentionally
excluded. The project's own source is © Scott Thomas Stone (see
[\`README.md\`](README.md)); this file covers third-party code only.

Every license below is a permissive OSI/SIL license (MIT, ISC, Apache-2.0,
BSD, 0BSD, or the SIL Open Font License for the bundled fonts) that allows
redistribution in a commercial or non-commercial product. A CI gate
(\`npm run licenses:check\`) fails the build if a dependency ever introduces a
license outside the reviewed allowlist.

- **Generated:** ${date}
- **Production packages:** ${rows.length}

## Summary

| License | Packages |
|---|---:|
${summary.map(([lic, n]) => `| ${esc(lic)} | ${n} |`).join('\n')}

## Fonts

The UI typefaces **Inter** and **Source Serif 4** are bundled (self-hosted, no
CDN) via \`@fontsource-variable/*\` and are licensed under the **SIL Open Font
License 1.1**, which permits embedding and redistribution. Their \`OFL.txt\`
notices ship inside the respective \`node_modules/@fontsource-variable/*\`
packages.

## All production dependencies

| Package | Version | License | Source |
|---|---|---|---|
${rows
  .map((r) => `| ${esc(r.name)} | ${esc(r.version)} | ${esc(r.license)} | ${r.repo ? esc(r.repo) : '—'} |`)
  .join('\n')}
`;

writeFileSync('THIRD-PARTY-LICENSES.md', out);
console.log(`Wrote THIRD-PARTY-LICENSES.md (${rows.length} production packages).`);
